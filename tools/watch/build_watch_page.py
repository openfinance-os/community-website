#!/usr/bin/env python3
"""Local preview builder for the Ecosystem Watch page.

The production page is built by the Astro endpoint
src/pages/observatory/watch/index.html.ts, which injects
data/watch/payload.json into tools/watch/watch.template.html at site build
time. This script does the same injection standalone so a payload can be
previewed without running the full site build:

    python3 tools/watch/build_watch_page.py \
        tools/watch/watch.template.html data/watch/payload.json /tmp/watch.html

Payload schema: see the `var D=__DATA__` consumer in the template and the
weekly-regulatory-watch job prompt (tools/watch/routine-prompt.md). The
`breaking` block is generated by
tools/watch/of_watch_breaking.py; the production adoption grid by
tools/watch/of_watch_production.py.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TEMPLATE = os.path.join(HERE, "watch.template.html")


def build(template_path, payload_path, out_path):
    payload = json.load(open(payload_path))  # validate JSON before injecting
    tmpl = open(template_path).read()
    if "__DATA__" not in tmpl:
        sys.exit(f"{template_path} is missing the __DATA__ placeholder")
    html = tmpl.replace("__DATA__", json.dumps(payload))
    open(out_path, "w").write(html)
    return len(html)


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 3:
        template, payload, out = args
    elif len(args) == 2:  # legacy: payload, out
        template, payload, out = DEFAULT_TEMPLATE, args[0], args[1]
    else:
        sys.exit("usage: build_watch_page.py <template.html> <payload.json> <out.html>")
    n = build(template, payload, out)
    print(f"wrote {out} ({n} bytes) from {os.path.basename(template)}")
