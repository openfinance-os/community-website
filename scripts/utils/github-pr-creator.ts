// GitHub API client for creating draft PRs with news articles
import type { CuratedArticle, GitHubPR } from '../types/news-curation.js';

const GITHUB_API_URL = 'https://api.github.com';

export interface GitHubOptions {
  token: string;
  owner: string;
  repo: string;
  baseBranch?: string;
}

interface GitHubRefResponse {
  object: {
    sha: string;
  };
}

interface GitHubBlobResponse {
  sha: string;
}

interface GitHubTreeResponse {
  sha: string;
}

interface GitHubCommitResponse {
  sha: string;
}

interface GitHubPRResponse {
  number: number;
  html_url: string;
}

function generateMarkdownContent(article: CuratedArticle): string {
  const date = new Date(article.publishedAt).toISOString().split('T')[0];

  return `---
title: "${article.title.replace(/"/g, '\\"')}"
date: ${date}
type: ${article.type}
region: ${article.region}
author: ${article.source}
source: ${article.sourceUrl}
description: "${article.summary.replace(/"/g, '\\"')}"
external: true
---

${article.summary}
`;
}

function generatePRBody(article: CuratedArticle): string {
  const publishedDate = new Date(article.publishedAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  return `## Article Details

| Field | Value |
|-------|-------|
| **Source** | ${article.source} |
| **Published** | ${publishedDate} |
| **Type** | ${article.type} |
| **Region** | ${article.region.toUpperCase()} |
| **Relevance Score** | ${article.relevanceScore} |

## Summary

${article.summary}

## Original Article

[Read full article](${article.sourceUrl})

---

## Actions

- **Merge** this PR to publish the article to the website
- **Close** this PR to reject the article

---

*Auto-generated by News Curation Bot*
*This PR will auto-close in 48 hours if not merged*
`;
}

async function githubRequest<T>(
  endpoint: string,
  options: GitHubOptions,
  method: string = 'GET',
  body?: object
): Promise<T> {
  const url = `${GITHUB_API_URL}${endpoint}`;

  const response = await fetch(url, {
    method,
    headers: {
      Authorization: `Bearer ${options.token}`,
      Accept: 'application/vnd.github+json',
      'Content-Type': 'application/json',
      'X-GitHub-Api-Version': '2022-11-28',
    },
    body: body ? JSON.stringify(body) : undefined,
  });

  if (!response.ok) {
    const error = await response.text();
    throw new Error(`GitHub API error: ${response.status} - ${error}`);
  }

  // Handle 204 No Content (e.g. DELETE responses)
  if (response.status === 204) {
    return undefined as T;
  }

  return response.json();
}

export interface FilePRInput {
  /** Branch to create/update (e.g. `news/slug` or `digest/2026-07-12`) */
  branchName: string;
  /** Repo-relative path of the file to add/replace */
  filePath: string;
  /** Full file contents */
  content: string;
  /** Commit message */
  commitMessage: string;
  /** Pull request title */
  prTitle: string;
  /** Pull request body (markdown) */
  prBody: string;
  /** Optional labels; failures to apply are non-fatal */
  labels?: string[];
  /**
   * When true, merge the PR immediately after creation instead of leaving it
   * open for manual review. Use only for deterministic, no-judgment-call
   * content (e.g. the weekly digest, computed entirely from data already
   * committed to the repo) — not for anything requiring editorial review
   * (e.g. curated external news articles).
   */
  autoMerge?: boolean;
  /** Merge method used when autoMerge is true. Defaults to 'squash'. */
  mergeMethod?: 'merge' | 'squash' | 'rebase';
}

/**
 * Generic single-file PR: commits `content` to `filePath` on a fresh branch
 * off the base branch and opens a PR. Used by both news curation and the
 * weekly digest so the GitHub plumbing lives in one place.
 */
export async function createFilePR(
  input: FilePRInput,
  options: GitHubOptions
): Promise<{ number: number; url: string; branch: string }> {
  const { owner, repo, baseBranch = 'main' } = options;
  const { branchName, filePath, content, commitMessage, prTitle, prBody, labels, autoMerge, mergeMethod } =
    input;

  // 1. Base branch SHA
  const baseRef = await githubRequest<GitHubRefResponse>(
    `/repos/${owner}/${repo}/git/ref/heads/${baseBranch}`,
    options
  );
  const baseSha = baseRef.object.sha;

  // 2. Blob
  const blob = await githubRequest<GitHubBlobResponse>(
    `/repos/${owner}/${repo}/git/blobs`,
    options,
    'POST',
    { content: Buffer.from(content).toString('base64'), encoding: 'base64' }
  );

  // 3. Tree
  const tree = await githubRequest<GitHubTreeResponse>(
    `/repos/${owner}/${repo}/git/trees`,
    options,
    'POST',
    {
      base_tree: baseSha,
      tree: [{ path: filePath, mode: '100644', type: 'blob', sha: blob.sha }],
    }
  );

  // 4. Commit
  const commit = await githubRequest<GitHubCommitResponse>(
    `/repos/${owner}/${repo}/git/commits`,
    options,
    'POST',
    { message: commitMessage, tree: tree.sha, parents: [baseSha] }
  );

  // 5. Branch (create, or force-update if it exists)
  try {
    await githubRequest(`/repos/${owner}/${repo}/git/refs`, options, 'POST', {
      ref: `refs/heads/${branchName}`,
      sha: commit.sha,
    });
  } catch {
    await githubRequest(`/repos/${owner}/${repo}/git/refs/heads/${branchName}`, options, 'PATCH', {
      sha: commit.sha,
      force: true,
    });
  }

  // 6. Pull request
  const pr = await githubRequest<GitHubPRResponse>(
    `/repos/${owner}/${repo}/pulls`,
    options,
    'POST',
    { title: prTitle, head: branchName, base: baseBranch, body: prBody, draft: false }
  );

  // 7. Labels (non-fatal)
  if (labels && labels.length > 0) {
    try {
      await githubRequest(`/repos/${owner}/${repo}/issues/${pr.number}/labels`, options, 'POST', {
        labels,
      });
    } catch {
      console.warn('Could not add labels to PR (labels may not exist)');
    }
  }

  console.log(`  Created PR #${pr.number}: ${pr.html_url}`);

  // 8. Auto-merge (opt-in, deterministic content only — see FilePRInput.autoMerge)
  if (autoMerge) {
    try {
      await githubRequest(`/repos/${owner}/${repo}/pulls/${pr.number}/merge`, options, 'PUT', {
        merge_method: mergeMethod || 'squash',
      });
      console.log(`  Auto-merged PR #${pr.number}`);
    } catch (err) {
      console.warn(`  Could not auto-merge PR #${pr.number} (left open for manual review):`, err);
    }
  }

  return { number: pr.number, url: pr.html_url, branch: branchName };
}

export async function createArticlePR(
  article: CuratedArticle,
  options: GitHubOptions
): Promise<GitHubPR> {
  console.log(`Creating PR for: ${article.title.substring(0, 50)}...`);
  try {
    const pr = await createFilePR(
      {
        branchName: `news/${article.slug}`,
        filePath: `src/content/news/${article.slug}.md`,
        content: generateMarkdownContent(article),
        commitMessage: `feat(news): add "${article.title.substring(0, 50)}..."`,
        prTitle: `[News] ${article.title}`,
        prBody: generatePRBody(article),
        labels: ['news-curation', 'auto-generated'],
      },
      options
    );
    return { number: pr.number, url: pr.url, title: article.title, branch: pr.branch };
  } catch (error) {
    console.error(`Failed to create PR for article: ${article.title}`, error);
    throw error;
  }
}

export async function createAllPRs(
  articles: CuratedArticle[],
  options: GitHubOptions
): Promise<Array<{ article: CuratedArticle; pr: GitHubPR }>> {
  const results: Array<{ article: CuratedArticle; pr: GitHubPR }> = [];

  for (const article of articles) {
    try {
      const pr = await createArticlePR(article, options);
      results.push({ article, pr });

      // Small delay to avoid rate limiting
      await new Promise((resolve) => setTimeout(resolve, 1000));
    } catch (error) {
      console.error(`Skipping article due to error: ${article.title}`);
    }
  }

  return results;
}

export async function closeOldPRs(
  options: GitHubOptions,
  maxAgeHours: number = 48
): Promise<number> {
  const { owner, repo } = options;
  let closedCount = 0;

  try {
    // Get open PRs with news-curation label
    const prsResponse = await githubRequest<
      Array<{ number: number; created_at: string; head: { ref: string } }>
    >(`/repos/${owner}/${repo}/pulls?state=open&per_page=100`, options);

    const cutoffTime = new Date();
    cutoffTime.setHours(cutoffTime.getHours() - maxAgeHours);

    for (const pr of prsResponse) {
      // Check if it's a news curation PR
      if (!pr.head.ref.startsWith('news/')) continue;

      const createdAt = new Date(pr.created_at);
      if (createdAt < cutoffTime) {
        console.log(`Closing stale PR #${pr.number} (created ${pr.created_at})`);

        // Close the PR
        await githubRequest(`/repos/${owner}/${repo}/pulls/${pr.number}`, options, 'PATCH', {
          state: 'closed',
        });

        // Delete the branch
        try {
          await githubRequest(
            `/repos/${owner}/${repo}/git/refs/heads/${pr.head.ref}`,
            options,
            'DELETE'
          );
        } catch {
          console.warn(`Could not delete branch ${pr.head.ref}`);
        }

        closedCount++;
      }
    }

    console.log(`Closed ${closedCount} stale PRs`);
    return closedCount;
  } catch (error) {
    console.error('Failed to close old PRs:', error);
    return closedCount;
  }
}
